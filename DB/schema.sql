-- 沸点火锅店点餐管理系统 MySQL 数据库设计
-- 文件说明：本脚本创建系统所需的用户、菜品、购物车、订单、评价和推荐相关数据表。
-- 执行顺序：先创建数据库，再创建基础表，最后创建带外键关系的业务表。
CREATE DATABASE IF NOT EXISTS cs_hotpot DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cs_hotpot;

CREATE TABLE IF NOT EXISTS `user` (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '用户主键',
  username VARCHAR(50) NOT NULL UNIQUE COMMENT '登录账号',
  password VARCHAR(100) NOT NULL COMMENT '登录密码（生产环境请加密）',
  nickname VARCHAR(50) NOT NULL COMMENT '用户昵称',
  phone VARCHAR(20) COMMENT '手机号',
  avatar VARCHAR(255) COMMENT '头像地址',
  role VARCHAR(20) NOT NULL DEFAULT 'USER' COMMENT 'USER/ADMIN',
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1启用 0禁用',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB COMMENT='用户表';

CREATE TABLE IF NOT EXISTS dishCategory (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  categoryName VARCHAR(50) NOT NULL COMMENT '分类名称',
  sortNumber INT NOT NULL DEFAULT 0,
  status TINYINT NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB COMMENT='菜品分类表';

CREATE TABLE IF NOT EXISTS dish (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  categoryId BIGINT NOT NULL,
  dishName VARCHAR(100) NOT NULL,
  description VARCHAR(255),
  coverImage VARCHAR(255),
  price DECIMAL(10,2) NOT NULL,
  saleNumber INT NOT NULL DEFAULT 0,
  isRecommended TINYINT NOT NULL DEFAULT 0,
  isNew TINYINT NOT NULL DEFAULT 0,
  status TINYINT NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fkDishCategory FOREIGN KEY (categoryId) REFERENCES dishCategory(id)
) ENGINE=InnoDB COMMENT='菜品信息表';

CREATE TABLE IF NOT EXISTS diningTable (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tableNumber VARCHAR(20) NOT NULL UNIQUE,
  seatNumber INT NOT NULL DEFAULT 4,
  tableStatus VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' COMMENT 'AVAILABLE/OCCUPIED/RESERVED',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB COMMENT='桌台表';

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  orderNumber VARCHAR(30) NOT NULL UNIQUE,
  userId BIGINT,
  tableId BIGINT,
  totalAmount DECIMAL(10,2) NOT NULL DEFAULT 0,
  orderStatus VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/CONFIRMED/COOKING/COMPLETED/CANCELLED',
  remark VARCHAR(255),
  orderedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completedAt DATETIME,
  CONSTRAINT fkOrderUser FOREIGN KEY (userId) REFERENCES `user`(id),
  CONSTRAINT fkOrderTable FOREIGN KEY (tableId) REFERENCES diningTable(id)
) ENGINE=InnoDB COMMENT='订单表';

CREATE TABLE IF NOT EXISTS orderItem (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  orderId BIGINT NOT NULL,
  dishId BIGINT NOT NULL,
  dishName VARCHAR(100) NOT NULL COMMENT '下单时菜品快照',
  unitPrice DECIMAL(10,2) NOT NULL,
  quantity INT NOT NULL DEFAULT 1,
  subtotal DECIMAL(10,2) NOT NULL,
  CONSTRAINT fkItemOrder FOREIGN KEY (orderId) REFERENCES orders(id),
  CONSTRAINT fkItemDish FOREIGN KEY (dishId) REFERENCES dish(id)
) ENGINE=InnoDB COMMENT='订单明细表';

CREATE TABLE IF NOT EXISTS cartItem (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  userId BIGINT NOT NULL,
  dishId BIGINT NOT NULL,
  quantity INT NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY ukUserDish (userId, dishId),
  CONSTRAINT fkCartUser FOREIGN KEY (userId) REFERENCES user(id),
  CONSTRAINT fkCartDish FOREIGN KEY (dishId) REFERENCES dish(id)
) ENGINE=InnoDB COMMENT='购物车表';

CREATE TABLE IF NOT EXISTS favoriteDish (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  userId BIGINT NOT NULL,
  dishId BIGINT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY ukFavoriteUserDish (userId,dishId),
  CONSTRAINT fkFavoriteUser FOREIGN KEY (userId) REFERENCES `user`(id),
  CONSTRAINT fkFavoriteDish FOREIGN KEY (dishId) REFERENCES dish(id)
) ENGINE=InnoDB COMMENT='收藏菜品表';

CREATE TABLE IF NOT EXISTS browseHistory (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  userId BIGINT NOT NULL,
  dishId BIGINT NOT NULL,
  browseCount INT NOT NULL DEFAULT 1,
  lastBrowsedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY ukBrowseUserDish (userId,dishId),
  CONSTRAINT fkBrowseUser FOREIGN KEY (userId) REFERENCES `user`(id),
  CONSTRAINT fkBrowseDish FOREIGN KEY (dishId) REFERENCES dish(id)
) ENGINE=InnoDB COMMENT='菜品浏览记录表';

CREATE TABLE IF NOT EXISTS dishReview (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  orderId BIGINT NOT NULL,
  userId BIGINT NOT NULL,
  dishId BIGINT,
  rating TINYINT NOT NULL,
  content VARCHAR(500),
  replyContent VARCHAR(500),
  userReplyContent VARCHAR(500),
  reviewStatus TINYINT NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fkReviewOrder FOREIGN KEY (orderId) REFERENCES orders(id),
  CONSTRAINT fkReviewUser FOREIGN KEY (userId) REFERENCES `user`(id),
  CONSTRAINT fkReviewDish FOREIGN KEY (dishId) REFERENCES dish(id)
) ENGINE=InnoDB COMMENT='评价表';

CREATE TABLE IF NOT EXISTS announcement (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  title VARCHAR(100) NOT NULL,
  content TEXT NOT NULL,
  publisherId BIGINT,
  publishStatus TINYINT NOT NULL DEFAULT 1,
  publishedAt DATETIME,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fkAnnouncementPublisher FOREIGN KEY (publisherId) REFERENCES `user`(id)
) ENGINE=InnoDB COMMENT='公告表';

